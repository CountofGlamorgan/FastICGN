# Check that every header `cmake --install` puts under
# <prefix>/include/opencorr-gpu/ is usable on its own: each one is compiled as
# the only include of a fresh translation unit, exactly as an embedding project
# would see it. A header that needs a file the install does not ship (a
# third_party/ header, an internal CLI header) fails here.
#
#   bash smoke/check_installed_headers.sh --prefix /path/to/install/prefix
#
# Options / environment:
#   --prefix DIR        install prefix (required; also $PREFIX)
#   --contract FILE     header list to cross-check (default docs/library-contracts.md)
#   CXX                 compiler (default c++)
#   EIGEN_INCLUDE_DIR   directory holding Eigen/Core (default: pkg-config, then
#                       the usual /usr/include/eigen3 style locations)
#   OPENCV_INCLUDE_DIR  OpenCV include root (default: pkg-config opencv4/opencv)
#   EXTRA_CXXFLAGS      appended to every compile

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
PREFIX="${PREFIX:-}"
CONTRACT="${REPO_ROOT}/docs/library-contracts.md"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --prefix) PREFIX="$2"; shift 2 ;;
    --contract) CONTRACT="$2"; shift 2 ;;
    -h|--help) sed -n '8,24p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "error: unknown argument: $1" >&2; exit 2 ;;
  esac
done

if [[ -z "${PREFIX}" ]]; then
  echo "error: --prefix (or \$PREFIX) is required" >&2
  exit 2
fi

INCLUDE_DIR="${PREFIX}/include/opencorr-gpu"
if [[ ! -d "${INCLUDE_DIR}" ]]; then
  echo "error: no installed headers at ${INCLUDE_DIR}" >&2
  echo "       Run: cmake --install <build-dir> --prefix ${PREFIX}" >&2
  exit 1
fi

CXX_BIN="${CXX:-c++}"
command -v "${CXX_BIN}" >/dev/null 2>&1 || { echo "error: no C++ compiler (${CXX_BIN})" >&2; exit 1; }

pkg_cflags() {  # first package name that pkg-config knows
  command -v pkg-config >/dev/null 2>&1 || return 1
  local name
  for name in "$@"; do
    if pkg-config --exists "${name}" 2>/dev/null; then
      pkg-config --cflags "${name}"
      return 0
    fi
  done
  return 1
}

# Eigen. The vendored OpenCorr headers use upstream's non-standard
# `#include <Eigen>` spelling, so the Eigen root and its Eigen/ subdirectory
# both go on the include path, exactly as CMakeLists.txt does it.
EIGEN_DIR="${EIGEN_INCLUDE_DIR:-}"
if [[ -z "${EIGEN_DIR}" ]]; then
  for candidate in /usr/include/eigen3 /usr/local/include/eigen3 /usr/include /usr/local/include; do
    if [[ -f "${candidate}/Eigen/Core" ]]; then EIGEN_DIR="${candidate}"; break; fi
  done
fi
EIGEN_FLAGS=()
if [[ -n "${EIGEN_DIR}" ]]; then
  EIGEN_FLAGS=(-I "${EIGEN_DIR}" -I "${EIGEN_DIR}/Eigen")
else
  read -r -a EIGEN_FLAGS <<<"$(pkg_cflags eigen3 || true)"
fi

read -r -a OPENCV_FLAGS <<<"${OPENCV_INCLUDE_DIR:+-I ${OPENCV_INCLUDE_DIR}}"
if [[ ${#OPENCV_FLAGS[@]} -eq 0 ]]; then
  read -r -a OPENCV_FLAGS <<<"$(pkg_cflags opencv4 opencv || true)"
fi

read -r -a EXTRA_FLAGS <<<"${EXTRA_CXXFLAGS:-}"

WORK_DIR="$(mktemp -d "${TMPDIR:-/tmp}/fasticgn-installed-headers-XXXXXX")"
trap 'rm -rf "${WORK_DIR}"' EXIT

mapfile -t HEADERS < <(cd "${INCLUDE_DIR}" && find . -type f \( -name '*.h' -o -name '*.hpp' \) \
  | sed 's|^\./||' | LC_ALL=C sort)

if [[ ${#HEADERS[@]} -eq 0 ]]; then
  echo "error: ${INCLUDE_DIR} contains no headers" >&2
  exit 1
fi

echo "Installed headers: ${#HEADERS[@]} under ${INCLUDE_DIR}"
echo "Compiler: $(${CXX_BIN} --version 2>/dev/null | head -1)"
[[ -n "${EIGEN_DIR}" ]] && echo "Eigen: ${EIGEN_DIR}"

# Vendored upstream headers that are not self-contained. We do not patch
# vendored sources (that would break the NOTICE baseline and the licence gate),
# so the probe supplies exactly the standard header upstream forgot and
# docs/library-contracts.md documents the requirement for embedders. Everything
# else in the header is still checked in isolation.
header_prelude() {
  case "$1" in
    # oc_point.h calls sqrt() in Point2D/Point3D::vectorNorm but includes only
    # <iostream>; it compiles in-tree because every dependent header pulls in
    # <cmath> first.
    oc_point.h) printf '#include <cmath>\n' ;;
    *) : ;;
  esac
}

FAILED=0
UNLISTED=0
PRELUDED=0
for header in "${HEADERS[@]}"; do
  source_file="${WORK_DIR}/probe.cpp"
  prelude="$(header_prelude "$(basename "${header}")")"
  {
    printf '// generated by smoke/check_installed_headers.sh\n'
    [[ -n "${prelude}" ]] && printf '%s\n' "${prelude}"
    printf '#include <opencorr-gpu/%s>\n' "${header}"
    printf 'int opencorr_installed_header_probe() { return 0; }\n'
  } >"${source_file}"
  if "${CXX_BIN}" -std=c++17 -c "${source_file}" -o "${WORK_DIR}/probe.o" \
      -I "${PREFIX}/include" -I "${INCLUDE_DIR}" \
      "${EIGEN_FLAGS[@]}" "${OPENCV_FLAGS[@]}" "${EXTRA_FLAGS[@]}" \
      >"${WORK_DIR}/probe.log" 2>&1; then
    status="OK  "
    if [[ -n "${prelude}" ]]; then
      status="OK+ "
      PRELUDED=$((PRELUDED + 1))
    fi
  else
    status="FAIL"
    FAILED=$((FAILED + 1))
  fi
  printf '  %s %s%s\n' "${status}" "${header}" \
    "${prelude:+   (upstream omission: needs a standard header first)}"
  if [[ "${status}" == "FAIL" ]]; then
    sed 's/^/        /' "${WORK_DIR}/probe.log" | head -20
  fi
  if [[ -f "${CONTRACT}" ]] && ! grep -qF "$(basename "${header}")" "${CONTRACT}"; then
    printf '  NOTE %s is installed but not listed in %s\n' "${header}" "${CONTRACT}"
    UNLISTED=$((UNLISTED + 1))
  fi
done

if [[ "${FAILED}" -ne 0 ]]; then
  echo "FAIL: ${FAILED} of ${#HEADERS[@]} installed headers do not compile standalone" >&2
  exit 1
fi
if [[ "${UNLISTED}" -ne 0 ]]; then
  echo "FAIL: ${UNLISTED} installed header(s) are not declared in ${CONTRACT}" >&2
  exit 1
fi
if [[ "${PRELUDED}" -ne 0 ]]; then
  echo "OK: ${#HEADERS[@]} installed headers compile and are declared" \
       "(${PRELUDED} needed a documented standard-header prelude)"
else
  echo "OK: all ${#HEADERS[@]} installed headers compile standalone and are declared"
fi
